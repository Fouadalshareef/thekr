export function getNextQuote(): string {
  let index = parseInt(localStorage.getItem('current_quote_index') || '0', 10)
  if (isNaN(index) || index < 0 || index >= DHIKR_QUOTES.length) {
    index = 0
  }
  
  const quote = DHIKR_QUOTES[index]
  
  // حفظ الفهرس التالي للمرة القادمة
  localStorage.setItem('current_quote_index', ((index + 1) % DHIKR_QUOTES.length).toString())
  
  return quote
}
